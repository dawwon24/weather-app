export function describe(code: number, isDay = 1): { text: string; icon: string } {
  const c = CODES[code];
  if (!c) return { text: '알 수 없음', icon: '❔' };
  return { text: c[0], icon: !isDay && c[2] ? c[2] : c[1] };
}
